#!/usr/bin/env node
/**
 * Generates local auth secrets for AiWave.
 *
 * Writes `.env.local` (git-ignored) with:
 *   - AUTH_SECRET               HMAC key used to sign session cookies
 *   - SUPERADMIN_EMAIL / NAME   seeded super-admin identity
 *   - SUPERADMIN_PASSWORD_HASH  scrypt hash of a freshly generated password
 *
 * The super-admin password is printed ONCE to the console — copy it now, it is
 * never stored in plaintext. The hash format matches src/lib/auth/password.ts
 * exactly (`scrypt:<saltHex>:<hashHex>`), so logins verify correctly.
 *
 * Usage:
 *   node scripts/gen-secrets.mjs            # creates .env.local (refuses if it exists)
 *   node scripts/gen-secrets.mjs --force    # overwrites an existing .env.local
 *
 * Never commit .env.local or the printed password.
 */
import { randomBytes, scrypt as scryptCb } from "node:crypto";
import { promisify } from "node:util";
import { writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scrypt = promisify(scryptCb);

// Keep these in lockstep with src/lib/auth/password.ts.
const PARAMS = { N: 16384, r: 8, p: 1, maxmem: 64 * 1024 * 1024 };
const KEY_LEN = 64;

async function hashPassword(password) {
  const salt = randomBytes(16);
  const derived = await scrypt(password, salt, KEY_LEN, PARAMS);
  return `scrypt:${salt.toString("hex")}:${derived.toString("hex")}`;
}

/** A readable, strong random password (no ambiguous chars). */
function generatePassword(len = 20) {
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
  const bytes = randomBytes(len);
  let out = "";
  for (let i = 0; i < len; i++) out += alphabet[bytes[i] % alphabet.length];
  return out;
}

async function main() {
  const force = process.argv.includes("--force");
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const envPath = path.join(root, ".env.local");

  if (existsSync(envPath) && !force) {
    console.error(
      `\n.env.local already exists at:\n  ${envPath}\n\n` +
        "Refusing to overwrite it (it may hold live secrets).\n" +
        "Re-run with --force to regenerate, or edit the file by hand.\n"
    );
    process.exit(1);
  }

  const authSecret = randomBytes(32).toString("base64url");
  const email = process.env.SUPERADMIN_EMAIL?.trim().toLowerCase() || "admin@aiwave.ai";
  const name = process.env.SUPERADMIN_NAME?.trim() || "Admin";
  const password = generatePassword();
  const passwordHash = await hashPassword(password);

  const body =
    "# Generated by scripts/gen-secrets.mjs — DO NOT COMMIT.\n" +
    "# Regenerate with: node scripts/gen-secrets.mjs --force\n\n" +
    `AUTH_SECRET=${authSecret}\n\n` +
    `SUPERADMIN_EMAIL=${email}\n` +
    `SUPERADMIN_NAME=${name}\n` +
    `SUPERADMIN_PASSWORD_HASH=${passwordHash}\n\n` +
    // We never invent DB credentials — leave a blank placeholder for the owner
    // to fill with the real "wave-ai" connection string.
    "# MySQL connection for the wave-ai database — fill this in yourself.\n" +
    "#   mysql://USER:PASSWORD@HOST:3306/wave-ai\n" +
    "# At scale route through a pooler — see .env.example.\n" +
    "DATABASE_URL=\n\n" +
    "# App / brand name (first-paint fallback; real name lives in BrandConfig).\n" +
    "APP_NAME=AiWave\n";

  writeFileSync(envPath, body, { encoding: "utf8", mode: 0o600 });

  console.log("\n  Wrote " + envPath);
  console.log("  AUTH_SECRET generated (32 bytes).\n");
  console.log("  Super-admin login (SAVE THIS NOW — shown only once):");
  console.log("    email:    " + email);
  console.log("    password: " + password + "\n");
  console.log("  The password is stored only as a scrypt hash. Restart the server to pick up .env.local.");
  console.log("  NOTE: set DATABASE_URL in .env.local to your wave-ai MySQL (port 3306) before running Prisma.\n");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
